def bank_tasks(story, lang):
    """Return independent, presentation-ready records for one story in ru or kk."""
    language_index = {"ru": 0, "kk": 1}[lang]
    missions = {"pizza": _PIZZA, "mars": _MARS}[story]
    tasks = []
    for number, points, titles, statements, cases in missions:
        examples = [
            {"input": raw_input, "output": output[language_index] if isinstance(output, tuple) else output}
            for raw_input, output in cases
        ]
        tasks.append({
            "number": number, "points": points, "title": titles[language_index],
            "statement": statements[language_index], "examples": examples,
        })
    return tasks
